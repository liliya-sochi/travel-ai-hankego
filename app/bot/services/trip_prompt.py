"""
Формирование запроса для AI.
"""


def build_trip_prompt(data: dict[str, str]) -> str:
    """
    Формирует подробный запрос для создания маршрута поездки.
    """

    return f"""
Ты — профессиональный AI-помощник по планированию путешествий.

Составь реалистичный и логичный маршрут поездки на основе данных пользователя.

Данные поездки:

Направление:
{data["destination"]}

Продолжительность:
{data["duration"]}

Бюджет:
{data["budget"]}

Интересы:
{data["interests"]}

Требования к маршруту:

1. Распредели программу по дням.
2. Не перегружай дни большим количеством мест.
3. Учитывай время на дорогу, отдых и приём пищи.
4. Подбирай места в соответствии с интересами пользователя.
5. Учитывай указанный бюджет.
6. Не придумывай точные цены, расписания и адреса, если не уверен.
7. Если данных недостаточно, используй разумные предположения.
8. Добавь краткие практические советы.
9. Не включай длинное вступление и лишние объяснения.
10. Ответ должен быть полезным для реальной поездки.
""".strip()